const assert=require('node:assert/strict');
const d=require('../DockPolicy.js');
const m=require('../ModulePolicy.js');
assert.equal(m.clean([...m.catalog.map(x=>x.id),...Array.from({length:30},(_,i)=>'dock:item-'+i)]).length,24);
assert.deepEqual(d.items([{id:'dock:a',kind:'link',name:'Bad',target:'https://secret@host/'},{id:'dock:b',kind:'file',target:'../file'},{id:'dock:c',kind:'app',target:'sh -c x'}]),[]);
assert.equal(d.items([{id:'dock:a',kind:'link',target:'https://example.org'},{id:'dock:a',kind:'spacer'}]).length,1);
const initial={modules:['music'],pins:[{id:'private.desktop'}],business:{path:'/secret'},timer:{status:'running'},activeDockProfile:'a',dockProfiles:[{id:'a',name:'One',layout:{modules:['music']}},{id:'b',name:'Two',layout:{modules:['timer']}}]};
const changed=d.update(initial,{modules:['music','stats']});
assert.deepEqual(changed.dockProfiles[0].layout.modules,['music','stats']);
const next=d.activate(changed,'b');assert.deepEqual(next.modules,['timer']);assert.deepEqual(next.timer,initial.timer);assert.equal(next.business.path,'/secret');
assert.deepEqual(d.activate(next,'a').modules,['music','stats']);
assert.equal(d.activate(next,'missing'),null);
const backup=d.backup(changed);assert(!backup.includes('private.desktop'));assert(!backup.includes('/secret'));assert(!backup.includes('running'));
assert.equal(d.restore(backup).dockProfiles.length,2);
assert.throws(()=>d.restore('{"format":"wrong","version":1,"profiles":[]}'));
assert.throws(()=>d.restore(' '.repeat(131073)));
assert.throws(()=>d.restore('{"format":"perch-docks","version":1,"profiles":[{}]}'));
const profile={id:'work',name:'Work',layout:{},schedule:{enabled:true,days:[1,2,3,4,5],start:540,end:1020}};
assert.equal(d.scheduled([profile],new Date(2026,9,5,9,0)).id,'work');
assert.equal(d.scheduled([profile],new Date(2026,9,5,17,0)),null);
assert.equal(d.scheduled([profile],new Date(2026,9,4,12,0)),null);
assert.equal(d.update({activeDockProfile:'work',dockProfiles:[profile]},{modules:['timer']}).dockProfiles[0].schedule.start,540);
console.log('Dock bounds, profile isolation, round-trip backups and schedule boundaries passed.');
